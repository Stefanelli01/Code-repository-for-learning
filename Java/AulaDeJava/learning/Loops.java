public class Loops {

    static void main() {

        System.out.println("Tabuada do 7");

        for (int i = 1; i <= 10; i++) {
            System.out.println("7 x " + i + " = " + (7 * i));
        }

        System.out.println("Contagem Regressiva");
        for (int i = 10; i >= 1; i--) {
            System.out.println(i);
        }
        System.out.println("Lançar!");
    }

}
